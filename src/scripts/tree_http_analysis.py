# (3) EXPORT LOGIC
# =============================================================================
def export_requests(all_requests_rows: list, export_path: str):
    """
    Exports granular HTTP request rows to CSV.
    One row per request with classification, entity, and technical metadata.

    Args:
        all_requests_rows: List of dicts from classify_requests()
        export_path:       Output CSV path
    """
    df = pd.DataFrame(all_requests_rows)
    df.to_csv(export_path, index=False)
    logger.info(f"Requests written:  {len(df)} rows → {export_path}")

def export_visit_summaries(visit_summary_rows: list, export_path: str):
    """
    Exports per-visit summary statistics to CSV.
    One row per site visit with aggregate counts per classification tier.

    Args:
        visit_summary_rows: List of dicts from classify_requests()
        export_path:        Output CSV path
    """
    df = pd.DataFrame(visit_summary_rows)
    df.to_csv(export_path, index=False)
    logger.info(f"Summaries written: {len(df)} rows → {export_path}")

def export_tracker_prevalence(tracker_prevalence: dict, export_path: str):
    """
    Aggregates tracker_prevalence into reach and volume statistics
    per third-party domain and exports to CSV.
        site_count  — reach:  number of unique sites on which this domain appeared
        visit_count — volume: number of unique visits in which this domain appeared

    Args:
        tracker_prevalence: defaultdict(set) from classify_requests()
        export_path:        Output CSV path
    """
    tracker_stats = []
    for domain, occurrences in tracker_prevalence.items():
        unique_sites = sorted({site for vid, site in occurrences if site})
        unique_vids  = sorted({vid  for vid, site in occurrences})

        tracker_stats.append({
            'third_party_domain': domain,
            'site_count':         len(unique_sites),
            'visit_count':        len(unique_vids),
            'sites_visited':      ", ".join(unique_sites),
            'visit_ids':          ", ".join(map(str, unique_vids))
        })

    tracker_df = pd.DataFrame(tracker_stats)
    if not tracker_df.empty:
        tracker_df = tracker_df.sort_values(by='site_count', ascending=False)

    tracker_df.to_csv(export_path, index=False)
    logger.info(f"Trackers written:  {len(tracker_df)} unique domains → {export_path}")

def export_results(all_requests_rows: list, visit_summary_rows: list, tracker_prevalence: dict):
    """
    Wrapper that triggers all three export helpers in sequence.

    Args:
        all_requests_rows : list of dicts from classify_requests()
        visit_summary_rows: list of dicts from classify_requests()
        tracker_prevalence: defaultdict(set) from classify_requests()
    """
    export_requests(all_requests_rows, OUTPUT_REQUESTS_CSV)
    export_visit_summaries(visit_summary_rows, OUTPUT_SUMMARIES_CSV)
    export_tracker_prevalence(tracker_prevalence, OUTPUT_TRACKERS_CSV)


# =============================================================================
# MAIN EXECUTION BLOCK
# =============================================================================
def main():
    logger.info("=== Starting HTTP Request Classification Pipeline ===")
    
    # Step 1: Load resources
    logger.info("--- Step 1: Loading Data and Entity Tree ---")
    site_visits_df, http_requests_df, incomplete_map = load_data()
    root, domain_to_node = load_tree(TREE_OUTPUT_CSV)
    
    # Step 2: Classify requests
    logger.info("--- Step 2: Classifying Requests ---")
    all_reqs, visit_sums, trackers, _ = classify_requests(
        site_visits_df, http_requests_df, incomplete_map, domain_to_node
    )
    
    # Step 3: Export results
    logger.info("--- Step 3: Exporting Results ---")
    export_results(all_reqs, visit_sums, trackers)
    logger.info(f"Files generated: {OUTPUT_REQUESTS_CSV}, {OUTPUT_SUMMARIES_CSV}, {OUTPUT_TRACKERS_CSV}")
    
    logger.info("=== Pipeline Execution Complete ===")

if __name__ == "__main__":
    main()