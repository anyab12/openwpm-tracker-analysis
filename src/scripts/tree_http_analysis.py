def load_data() -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    """
    Connects to SQLite database and loads all necessary DataFrames
    and lookup structures for classification pipeline.

    Returns:
        site_visits_df  : DataFrame of all site visits (visit_id, site_url)
        http_requests_df: DataFrame of all HTTP requests
        incomplete_map  : dict {visit_id: timeout_command} for incomplete visits
    """
    conn = sqlite3.connect(DB_PATH)

    # --- site_visits: anchor for the outer loop ---
    site_visits_df = pd.read_sql_query(
        "SELECT visit_id, site_url FROM site_visits", conn
    )

    # --- incomplete_visits + crawl_history join ---
    # For each incomplete visit_id, find the LAST command recorded in
    # crawl_history using SQLite's implicit rowid as an ordering key.
    # That command is the one that timed out.
    incomplete_query = """
        SELECT
            iv.visit_id,
            ch.command AS timeout_command
        FROM incomplete_visits iv
        LEFT JOIN crawl_history ch
            ON iv.visit_id = ch.visit_id
        WHERE ch.rowid = (
            SELECT MAX(ch2.rowid)
            FROM crawl_history ch2
            WHERE ch2.visit_id = iv.visit_id
        )
    """
    incomplete_df  = pd.read_sql_query(incomplete_query, conn)

    # Build a lookup dict where {visit_id: timeout_command_string}
    incomplete_map = dict(
        zip(incomplete_df['visit_id'], incomplete_df['timeout_command'])
    )

    # --- http_requests: data for the inner classification loop ---
    requests_query = """
        SELECT
            visit_id,
            request_id,
            url,
            top_level_url,
            resource_type,
            referrer
        FROM http_requests
    """
    http_requests_df = pd.read_sql_query(requests_query, conn)
    conn.close()

    logger.info(f"Incomplete visits found: {len(incomplete_map)}")
    logger.info(f"Breakdown: {pd.Series(incomplete_map).value_counts().to_dict()}")
    logger.info(f"Loaded {len(site_visits_df)} site visits.")
    logger.info(f"Loaded {len(http_requests_df)} HTTP requests.")

    return site_visits_df, http_requests_df, incomplete_map


# =============================================================================
# (2) CLASSIFICATION LOOP
# =============================================================================
def classify_requests(
        site_visits_df: pd.DataFrame,
        http_requests_df: pd.DataFrame,
        incomplete_map: dict,
        domain_to_node: dict
    ) -> tuple[list, list, dict, dict]:
    """
    Iterates over every site visit and every HTTP request within it,
    classifying each request using two-level parent/subsidiary hierarchy:

        first-party:              parent == top_parent AND subsidiary == top_subsidiary
        inter-family third-party: parent == top_parent AND subsidiary != top_subsidiary
        external third-party:     parent != top_parent (subsidiary irrelevant)
        unknown:                  domain unresolvable via get_registered_domain()

    Also records is_technical_3p — whether request domain differs from
    top-level domain at raw eTLD+1 level, regardless of entity classification.

    Classification logic is delegated to classify_relationship(), which handles
    both entity attribute access and unknown domain pass-through fallback.

    Args:
        site_visits_df  : DataFrame from load_data()
        http_requests_df: DataFrame from load_data()
        incomplete_map  : dict from load_data()
        domain_to_node  : dict from load_tree()

    Returns:
        all_requests_rows : list of dicts — one per HTTP request
        visit_summary_rows: list of dicts — one per site visit
        tracker_prevalence: defaultdict(set) — {third-party domain: {(visit_id, top_domain), ...}}
        first_party_coverage: defaultdict(int) — {first-party domain: visit_count}
    """

    tracker_prevalence   = defaultdict(set)
    first_party_coverage = defaultdict(int)
    all_requests_rows    = []
    visit_summary_rows   = []

    # OUTER LOOP — one iteration per site visit
    for _, visit in site_visits_df.iterrows():
        v_id            = visit['visit_id']
        site_url        = visit['site_url']
        timeout_command = incomplete_map.get(v_id, None)
        visit_complete  = 0 if timeout_command is not None else 1

        visit_requests   = http_requests_df[http_requests_df['visit_id'] == v_id].copy()
        visit_top_domain = get_registered_domain(site_url)

        if visit_top_domain:
            first_party_coverage[visit_top_domain] += 1

        counts = {
            "first-party": 0,
            "inter-family third-party": 0,
            "external third-party": 0,
            "unknown": 0
        }
        visit_third_party_domains = set()

        # INNER LOOP — one iteration per HTTP request within this visit
        for _, req in visit_requests.iterrows():
            req_url        = req['url']
            req_domain     = get_registered_domain(req_url)
            req_top_domain = get_registered_domain(req['top_level_url']) or visit_top_domain

            # Top-level and request node lookups
            # Pass-through fallback handled in get_node_info()
            top_node = get_node_info(req_top_domain, domain_to_node)
            req_node = get_node_info(req_domain, domain_to_node)

            # Unknown domain guard - skip classification if unresolvable
            if not req_domain or not req_top_domain:
                classification   = "unknown"
                is_tp_val        = None
                is_technical_3p  = None
                req_sub          = None
                req_parent       = None
                counts["unknown"] += 1

            else:
                # Attribute extraction — fallback to eTLD+1 string if node not in tree
                req_sub    = req_node.subsidiary_entity
                req_parent = req_node.parent_entity
                
                # Technical 3P check by raw eTLD+1 comparison, statistic + gate before entity lookup
                is_technical_3p = int(req_domain != req_top_domain)

                # Two-level hierarchy classification
                if is_technical_3p == 0:
                    # Domains identical — must be first-party, no tree lookup needed
                    classification = "first-party"
                    is_tp_val      = 0
                    counts["first-party"] += 1

                else:
                    # Domains differ — delegate to entity-aware classification
                    result = classify_relationship(req_node, top_node)

                    if result["is_parent_third_party"]:
                        # Different parent and subsidiary entities
                        classification = "external third-party"
                        is_tp_val      = 1
                        counts["external third-party"] += 1
                        tracker_prevalence[req_domain].add((v_id, req_top_domain))
                        visit_third_party_domains.add(req_domain)

                    elif result["is_subsidiary_third_party"]:
                        # Different subsidiary but same parent entities
                        classification = "inter-family third-party"
                        is_tp_val      = 1
                        counts["inter-family third-party"] += 1
                        tracker_prevalence[req_domain].add((v_id, req_top_domain))
                        visit_third_party_domains.add(req_domain)

                    else:
                        # Domains differ but entity resolves to same parent — first-party
                        classification = "first-party"
                        is_tp_val      = 0
                        counts["first-party"] += 1

            # Append stats row for each request
            all_requests_rows.append({
                'visit_id':              v_id,
                'request_id':            req['request_id'],
                'url':                   req_url,
                'request_domain':        req_domain,
                'request_subsidiary':    req_sub,
                'request_parent':        req_parent,
                'top_level_domain':      req_top_domain,
                'is_technical_3p':       is_technical_3p,
                'is_third_party':        is_tp_val,
                'classification':        classification,
                'resource_type':         req['resource_type'],
                'referrer':              req['referrer'],
                'visit_complete':        visit_complete,
            })

        # END INNER LOOP
        # Append summary row after all requests per visit are processed
        visit_summary_rows.append({
            'visit_id':                v_id,
            'site_url':                site_url,
            'visit_complete':          visit_complete,
            'timeout_command':         timeout_command,
            'total_requests':          len(visit_requests),
            'first_party_count':       counts["first-party"],
            'inter_family_tp_count':   counts["inter-family third-party"],
            'external_tp_count':       counts["external third-party"],
            'unknown_count':           counts["unknown"],
            'third_party_domains':     ", ".join(sorted(visit_third_party_domains))
        })

    logger.info(f"Classified {len(all_requests_rows)} total requests from {len(visit_summary_rows)} total visits.")
    
    return all_requests_rows, visit_summary_rows, tracker_prevalence, first_party_coverage


